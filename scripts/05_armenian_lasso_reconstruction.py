#!/usr/bin/env python3
"""
Reconstructed LASSO stability-selection and repeated-CV workflow for the
Armenian aggression analysis.

IMPORTANT REPRODUCIBILITY NOTE
------------------------------
The historical random seed and the exact historical CV split objects used to
produce the frozen Supplementary tables were not preserved. The selected
penalties (alpha_min and alpha_1se), sample definitions, coding rules, and
analysis design *were* preserved.

Accordingly, this script is a transparent stochastic reconstruction:
- it uses the exact frozen alpha_min and alpha_1se values from S3b/S3c;
- it reproduces the original strict sample and seven primary genetic codings;
- it uses a newly fixed random seed (default: 2026);
- it residualizes age inside each subsample/training fold;
- it standardizes genetic predictors and residualized outcomes using training
  data only;
- it performs 500 70% subsamples for stability selection;
- it performs repeated 5-fold CV with 10 repeats for predictive evaluation.

Because the historical random state is unavailable, selection frequencies and
fold-level R2 values generated by this script are expected to be close in
pattern but not bit-for-bit identical to frozen S3b/S3c. The frozen tables
remain the archival record of the historical stochastic run.

Restricted participant-level data remain outside the public repository.

Required local input
--------------------
data/Armenian_full_analysis.xlsx
  sheet: "первичные данные"

Outputs
-------
outputs/S3b_LASSO_reconstructed.csv
outputs/S3c_LASSO_CV_reconstructed.csv
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from sklearn.linear_model import Lasso, LinearRegression
from sklearn.metrics import r2_score
from sklearn.model_selection import RepeatedKFold
from sklearn.preprocessing import StandardScaler


TRAITS = ("PhA", "VerbA", "Ang", "Host", "Proact_ag", "React_ag")
GENES = (
    "AR_CAG",
    "HTR2C",
    "OXTRrs53576",
    "HTR2Ars6311",
    "BDNF rs6265",
    "ERCC5",
    "DRD4eIII",
)
SEX_LABEL = {1: "men", 2: "women"}
STRICT_OUTLIER_EXCEL_ROWS = {69, 72, 125, 181}

FROZEN_ALPHA: Dict[Tuple[int, str], Tuple[float, float]] = {
    (1, "PhA"): (0.06464349596716197, 0.2864108603253449),
    (1, "VerbA"): (0.19560442231600553, 0.19560442231600553),
    (1, "Ang"): (0.16054802838048413, 0.16054802838048413),
    (1, "Host"): (0.074464795795912, 0.30061566578596494),
    (1, "Proact_ag"): (0.1722913309605828, 0.1722913309605828),
    (1, "React_ag"): (0.13287452611269007, 0.21157382160258806),
    (2, "PhA"): (0.1120685680330456, 0.1120685680330456),
    (2, "VerbA"): (0.05964298006793443, 0.24077973988838158),
    (2, "Ang"): (0.16422378241266802, 0.16422378241266802),
    (2, "Host"): (0.14988809304383247, 0.14988809304383247),
    (2, "Proact_ag"): (0.1210369904401509, 0.1210369904401509),
    (2, "React_ag"): (0.13670154307111176, 0.13670154307111176),
}

EXPECTED_N = {
    (1, "PhA"): 63,
    (1, "VerbA"): 63,
    (1, "Ang"): 63,
    (1, "Host"): 63,
    (1, "Proact_ag"): 63,
    (1, "React_ag"): 63,
    (2, "PhA"): 105,
    (2, "VerbA"): 105,
    (2, "Ang"): 104,
    (2, "Host"): 105,
    (2, "Proact_ag"): 104,
    (2, "React_ag"): 104,
}


def parse_ar(value) -> Optional[List[float]]:
    if pd.isna(value):
        return None
    numbers = [float(x) for x in re.findall(r"\d+(?:\.\d+)?", str(value))]
    return numbers or None


def allele_dosage(value, allele: str) -> Optional[float]:
    if pd.isna(value):
        return None
    s = str(value).upper().replace("/", "").replace("-", "").replace(" ", "")
    if len(s) != 2 or any(ch not in "ACGT" for ch in s):
        return None
    return float(s.count(allele.upper()))


def parse_drd4(value) -> Optional[float]:
    if pd.isna(value):
        return None
    numbers = [int(x) for x in re.findall(r"\d+", str(value))]
    if len(numbers) < 2:
        return None
    return float(max(numbers[:2]) >= 7)


def genotype_value(row: pd.Series, gene: str, sex: int) -> Optional[float]:
    value = row.get(gene)

    if gene == "AR_CAG":
        alleles = parse_ar(value)
        if not alleles:
            return None
        if sex == 1:
            return float(alleles[0] >= 23)
        if len(alleles) < 2:
            return None
        return float(((alleles[0] + alleles[1]) / 2.0) >= 22)

    if gene == "HTR2C":
        if pd.isna(value):
            return None
        s = str(value).strip().upper()
        if sex == 1:
            if s.startswith("C"):
                return 1.0
            if s.startswith("G"):
                return 0.0
            return None
        return allele_dosage(value, "C")

    if gene == "OXTRrs53576":
        return allele_dosage(value, "A")
    if gene == "HTR2Ars6311":
        return allele_dosage(value, "A")
    if gene == "BDNF rs6265":
        return allele_dosage(value, "A")
    if gene == "ERCC5":
        return allele_dosage(value, "T")
    if gene == "DRD4eIII":
        return parse_drd4(value)

    raise KeyError(gene)


def clean_outcome(value, trait: str) -> Optional[float]:
    if pd.isna(value):
        return None
    x = float(value)
    if trait == "Ang" and x == 50:
        return None
    return x


def collect_dataset(df: pd.DataFrame, sex: int, trait: str):
    X: List[List[float]] = []
    y: List[float] = []
    age: List[float] = []

    for idx, row in df.iterrows():
        excel_row = int(idx) + 2
        if int(row["SEX"]) != sex:
            continue
        if excel_row in STRICT_OUTLIER_EXCEL_ROWS:
            continue
        if pd.isna(row["AGE"]):
            continue

        outcome = clean_outcome(row[trait], trait)
        if outcome is None:
            continue

        g = [genotype_value(row, gene, sex) for gene in GENES]
        if any(value is None for value in g):
            continue

        X.append([float(value) for value in g])
        y.append(outcome)
        age.append(float(row["AGE"]))

    X_arr = np.asarray(X, dtype=float)
    y_arr = np.asarray(y, dtype=float)
    age_arr = np.asarray(age, dtype=float)

    expected = EXPECTED_N[(sex, trait)]
    if len(y_arr) != expected:
        raise RuntimeError(
            f"Unexpected strict complete-case N for {SEX_LABEL[sex]} {trait}: "
            f"observed {len(y_arr)}, expected {expected}."
        )

    return X_arr, y_arr, age_arr


def residualize_train(y_train, age_train):
    model = LinearRegression().fit(age_train.reshape(-1, 1), y_train)
    residual = y_train - model.predict(age_train.reshape(-1, 1))
    return model, residual


def stream_seed(base_seed: int, sex: int, trait: str, purpose: int) -> int:
    return int(base_seed + 1000 * purpose + 100 * sex + TRAITS.index(trait))


def stability_selection(
    X: np.ndarray,
    y: np.ndarray,
    age: np.ndarray,
    alpha: float,
    seed: int,
    n_subsamples: int,
    fraction: float,
):
    rng = np.random.default_rng(seed)
    n = len(y)
    sample_size = int(np.floor(fraction * n))
    coefficients = np.zeros((n_subsamples, X.shape[1]), dtype=float)

    for i in range(n_subsamples):
        selected = rng.choice(n, size=sample_size, replace=False)
        X_sub = X[selected]
        y_sub = y[selected]
        age_sub = age[selected]

        _, y_residual = residualize_train(y_sub, age_sub)
        x_scaler = StandardScaler().fit(X_sub)
        y_scaler = StandardScaler().fit(y_residual.reshape(-1, 1))

        X_std = x_scaler.transform(X_sub)
        y_std = y_scaler.transform(y_residual.reshape(-1, 1)).ravel()

        model = Lasso(
            alpha=alpha,
            fit_intercept=True,
            max_iter=100000,
            tol=1e-10,
            selection="cyclic",
        ).fit(X_std, y_std)
        coefficients[i] = model.coef_

    nonzero = np.abs(coefficients) > 1e-10
    positive = coefficients > 1e-10
    negative = coefficients < -1e-10

    selection_frequency = nonzero.mean(axis=0)
    positive_frequency = positive.mean(axis=0)
    negative_frequency = negative.mean(axis=0)

    median_when_selected = np.zeros(X.shape[1], dtype=float)
    sign_consistency = np.zeros(X.shape[1], dtype=float)
    for j in range(X.shape[1]):
        selected_coef = coefficients[nonzero[:, j], j]
        if len(selected_coef):
            median_when_selected[j] = float(np.median(selected_coef))
            sign_consistency[j] = float(
                max(positive_frequency[j], negative_frequency[j])
                / selection_frequency[j]
            )
        else:
            median_when_selected[j] = 0.0
            sign_consistency[j] = np.nan

    return {
        "selection_frequency": selection_frequency,
        "positive_frequency": positive_frequency,
        "negative_frequency": negative_frequency,
        "sign_consistency": sign_consistency,
        "median_when_selected": median_when_selected,
    }


def cv_for_alpha(
    X: np.ndarray,
    y: np.ndarray,
    age: np.ndarray,
    alpha: float,
    seed: int,
    n_splits: int,
    n_repeats: int,
):
    splitter = RepeatedKFold(
        n_splits=n_splits,
        n_repeats=n_repeats,
        random_state=seed,
    )

    pooled_true: List[float] = []
    pooled_pred: List[float] = []
    fold_r2: List[float] = []

    for train_index, test_index in splitter.split(X):
        X_train, X_test = X[train_index], X[test_index]
        y_train, y_test = y[train_index], y[test_index]
        age_train, age_test = age[train_index], age[test_index]

        age_model, y_train_residual = residualize_train(y_train, age_train)
        y_test_residual = y_test - age_model.predict(age_test.reshape(-1, 1))

        x_scaler = StandardScaler().fit(X_train)
        y_scaler = StandardScaler().fit(y_train_residual.reshape(-1, 1))

        X_train_std = x_scaler.transform(X_train)
        X_test_std = x_scaler.transform(X_test)
        y_train_std = y_scaler.transform(
            y_train_residual.reshape(-1, 1)
        ).ravel()

        model = Lasso(
            alpha=alpha,
            fit_intercept=True,
            max_iter=100000,
            tol=1e-10,
            selection="cyclic",
        ).fit(X_train_std, y_train_std)

        pred_std = model.predict(X_test_std)
        pred = y_scaler.inverse_transform(pred_std.reshape(-1, 1)).ravel()

        pooled_true.extend(y_test_residual.tolist())
        pooled_pred.extend(pred.tolist())
        fold_r2.append(float(r2_score(y_test_residual, pred)))

    pooled_r2 = float(r2_score(np.asarray(pooled_true), np.asarray(pooled_pred)))
    q1, median, q3 = np.quantile(np.asarray(fold_r2), [0.25, 0.50, 0.75])
    return {
        "pooled_R2": pooled_r2,
        "median_fold_R2": float(median),
        "Q1_fold_R2": float(q1),
        "Q3_fold_R2": float(q3),
    }


def stability_class(freq: float) -> str:
    if freq >= 0.70:
        return "stable (>=0.70)"
    if freq >= 0.50:
        return "moderate (0.50-0.69)"
    if freq >= 0.30:
        return "weak (0.30-0.49)"
    return "unstable (<0.30)"


def run(df, seed: int, n_subsamples: int, fraction: float, n_repeats: int):
    stability_rows: List[Dict] = []
    cv_rows: List[Dict] = []

    for sex in (1, 2):
        for trait in TRAITS:
            X, y, age = collect_dataset(df, sex, trait)
            alpha_min, alpha_1se = FROZEN_ALPHA[(sex, trait)]

            stable = stability_selection(
                X,
                y,
                age,
                alpha_1se,
                seed=stream_seed(seed, sex, trait, purpose=1),
                n_subsamples=n_subsamples,
                fraction=fraction,
            )

            for j, gene in enumerate(GENES):
                stability_rows.append({
                    "Sex": SEX_LABEL[sex],
                    "Trait": trait,
                    "Gene": gene,
                    "N": len(y),
                    "Penalty": "lambda_1se",
                    "frozen alpha_min": alpha_min,
                    "frozen alpha_1se": alpha_1se,
                    "reconstruction seed": seed,
                    "Selection frequency": stable["selection_frequency"][j],
                    "Positive-sign frequency": stable["positive_frequency"][j],
                    "Negative-sign frequency": stable["negative_frequency"][j],
                    "Sign consistency": stable["sign_consistency"][j],
                    "Median standardized beta when selected": stable[
                        "median_when_selected"
                    ][j],
                    "Stability class": stability_class(
                        float(stable["selection_frequency"][j])
                    ),
                })

            cv_min = cv_for_alpha(
                X,
                y,
                age,
                alpha_min,
                seed=stream_seed(seed, sex, trait, purpose=2),
                n_splits=5,
                n_repeats=n_repeats,
            )
            cv_1se = cv_for_alpha(
                X,
                y,
                age,
                alpha_1se,
                seed=stream_seed(seed, sex, trait, purpose=2),
                n_splits=5,
                n_repeats=n_repeats,
            )

            cv_rows.append({
                "Sex": SEX_LABEL[sex],
                "Trait": trait,
                "N": len(y),
                "frozen alpha_min": alpha_min,
                "frozen alpha_1se": alpha_1se,
                "reconstruction seed": seed,
                "pooled R2 lambda_min": cv_min["pooled_R2"],
                "median fold R2 lambda_min": cv_min["median_fold_R2"],
                "Q1 fold R2 lambda_min": cv_min["Q1_fold_R2"],
                "Q3 fold R2 lambda_min": cv_min["Q3_fold_R2"],
                "pooled R2 lambda_1se": cv_1se["pooled_R2"],
                "median fold R2 lambda_1se": cv_1se["median_fold_R2"],
                "Q1 fold R2 lambda_1se": cv_1se["Q1_fold_R2"],
                "Q3 fold R2 lambda_1se": cv_1se["Q3_fold_R2"],
            })

    stability_df = pd.DataFrame(stability_rows).sort_values(
        ["Selection frequency", "Sex", "Trait", "Gene"],
        ascending=[False, True, True, True],
    )
    cv_df = pd.DataFrame(cv_rows)
    return stability_df, cv_df


def validate_structure(stability_df, cv_df):
    if len(stability_df) != 84:
        raise RuntimeError(f"Expected 84 stability rows, observed {len(stability_df)}")
    if len(cv_df) != 12:
        raise RuntimeError(f"Expected 12 CV rows, observed {len(cv_df)}")
    if int((stability_df["Selection frequency"] >= 0.70).sum()) != 0:
        raise RuntimeError(
            "Reconstructed run unexpectedly produced a stability frequency >=0.70; "
            "inspect before interpretation."
        )
    print("Structural validation PASSED: 84 stability rows and 12 CV models.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--armenian",
        type=Path,
        default=Path("data/Armenian_full_analysis.xlsx"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("outputs"))
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--n-subsamples", type=int, default=500)
    parser.add_argument("--subsample-fraction", type=float, default=0.70)
    parser.add_argument("--cv-repeats", type=int, default=10)
    args = parser.parse_args()

    df = pd.read_excel(args.armenian, sheet_name="первичные данные")
    args.output_dir.mkdir(parents=True, exist_ok=True)

    stability_df, cv_df = run(
        df,
        seed=args.seed,
        n_subsamples=args.n_subsamples,
        fraction=args.subsample_fraction,
        n_repeats=args.cv_repeats,
    )

    stability_df.to_csv(
        args.output_dir / "S3b_LASSO_reconstructed.csv", index=False
    )
    cv_df.to_csv(
        args.output_dir / "S3c_LASSO_CV_reconstructed.csv", index=False
    )

    validate_structure(stability_df, cv_df)

    print("\nTop reconstructed lambda_1se selection frequencies:")
    print(
        stability_df[
            ["Sex", "Trait", "Gene", "Selection frequency"]
        ].head(10).to_string(index=False)
    )
    print(
        "\nNOTE: these stochastic values are a seeded reconstruction, not a "
        "bit-for-bit recreation of the historical S3b/S3c run."
    )


if __name__ == "__main__":
    main()
